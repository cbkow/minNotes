#!/usr/bin/env python3
"""Generate tests/fixtures/type-probe.md — the type probe's document (A0 speed programme).

Deterministic: N repeated sections of {H2, three paragraphs (the first carries bold /
italic / code / link spans), a 6-row × 8-column GFM table with a checkbox column, a
20-line python block, six tasks, five ordered items, a quote, a divider}. Every
paragraph is ≥ 140 characters so the backspace phase has room. Around 1,600 model
rows at N = 20 (table cells are rows), which keeps the probe over its 1,000-block
arming threshold with a dense viewport in the middle.

    python3 scripts/gen_type_fixture.py [N] [out.md]
"""
import sys
from pathlib import Path

N = int(sys.argv[1]) if len(sys.argv) > 1 else 20
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "type-probe.md"

PLAIN = ("Measurement before design. A paragraph in the dense middle of the document receives "
         "one character per tick while the probe records the model's splits and the frame times, "
         "so the before and after tables line up section by section.")
SPANS = ("Spans change the cost: **bold runs**, *italic asides*, `inline code` and a "
         "[link to the docs](https://example.com/docs) all ride the highlighter, which today re-runs "
         "over every visible block on every keystroke anywhere in the document.")
THIRD = ("The third paragraph is plain again so the pool holds a mix of span-bearing and plain "
         "blocks in the same viewport, with a table, a code block, tasks and a list below it, "
         "which is the shape a real working document has.")

CODE = "\n".join([
    "def measure(samples):",
    "    \"\"\"p50 / p95 / max in microseconds.\"\"\"",
    "    if not samples:",
    "        return (0, 0, 0)",
    "    s = sorted(samples)",
    "    n = len(s)",
    "    p50 = s[int(0.50 * (n - 1))]",
    "    p95 = s[int(0.95 * (n - 1))]",
    "    return (p50, p95, s[-1])",
    "",
    "",
    "class Probe:",
    "    def __init__(self, name):",
    "        self.name = name",
    "        self.samples = []",
    "",
    "    def mark(self, us):",
    "        self.samples.append(us)",
    "",
    "    def stats(self):",
    "        return measure(self.samples)",
])

HEADER = "| Item | Owner | Status | Notes | Count | Done | Area | Ref |"
DELIM = "|---|---|---|---|---|:---:|---|---|"


def section(i: int) -> str:
    rows = [HEADER, DELIM]
    for r in range(6):
        done = "[x]" if r % 2 else "[ ]"
        rows.append(f"| Item {i}-{r} | Owner {r} | Status {r % 3} | Short note {r} for row {r} | {r * 7} | {done} | Area {r % 4} | R{i}{r} |")
    tasks = "\n".join(f"- [{'x' if t == 2 else ' '}] Task {t} of section {i}: a short line of work to do" for t in range(6))
    ordered = "\n".join(f"{t + 1}. Ordered item {t + 1} in section {i}" for t in range(5))
    return "\n".join([
        f"## Section {i}: probe material",
        "",
        PLAIN,
        "",
        SPANS,
        "",
        THIRD,
        "",
        "\n".join(rows),
        "",
        "```python",
        CODE,
        "```",
        "",
        tasks,
        "",
        ordered,
        "",
        f"> A quoted line in section {i}, kept short.",
        "",
        "---",
        "",
    ])


def main() -> None:
    body = "# Type probe fixture\n\nGenerated by scripts/gen_type_fixture.py. Do not edit by hand.\n\n"
    body += "".join(section(i) for i in range(N))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT} ({N} sections, {len(body)} bytes)")


if __name__ == "__main__":
    main()
